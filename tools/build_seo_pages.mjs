const OK_RIGHTS = new Set(['own-work', 'cleared', 'public-domain']);

function publishableTranslations(v) {
  const tr = v.translation || {};
  const rights = tr.rights || {};
  const out = [];
  for (const lang of Object.keys(tr)) {
    if (lang === 'provenance' || lang === 'rights') continue;
    const st = rights[lang]?.status;
    if (st && OK_RIGHTS.has(st)) {
      out.push({ lang, text: tr[lang], status: st, rights: rights[lang] });
    }
  }
  return out;
}

