const PAIRS = { '{': '}', '(': ')', '[': ']' };

function prevSig(text, i) {
  let j = i - 1;
  while (j >= 0 && /\s/.test(text[j])) j--;
  return j >= 0 ? text[j] : '';
}

function matchDelimiter(text, start) {
  // start points at an opener; return index of its matching closer.
  // Skips ' " ` strings, // and /* */ comments, and regex literals
  // (division vs regex decided by the previous significant character).
  const open = text[start], close = PAIRS[open];
  let depth = 0, inStr = null;
  for (let i = start; i < text.length; i++) {
    const c = text[i], n = text[i + 1];
    if (inStr) {
      if (c === '\\') { i++; continue; }
      if (c === inStr) inStr = null;
      continue;
    }
    if (c === "'" || c === '"' || c === '`') { inStr = c; continue; }
    if (c === '/' && n === '/') { while (i < text.length && text[i] !== '\n') i++; continue; }
    if (c === '/' && n === '*') {
      i += 2;
      while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) i++;
      continue;
    }
    if (c === '/' && /[([{=:,;!&|?~^+\-*%<>^-]/.test(prevSig(text, i))) {
      // regex literal — skip to its closing slash, honouring [...] classes
      let j = i + 1, inClass = false;
      while (j < text.length) {
        const rc = text[j];
        if (rc === '\\') { j += 2; continue; }
        if (rc === '[') inClass = true;
        else if (rc === ']') inClass = false;
        else if (rc === '/' && !inClass) break;
        j++;
      }
      i = j + 1;
      continue;
    }
    if (c === open) depth++;
    else if (c === close) { depth--; if (depth === 0) return i; }
  }
  throw new Error(`unbalanced ${open} at offset ${start}`);
}

function extractConst(src, name) {
  const m = src.match(new RegExp(`\\bconst ${name}\\s*=`));
  if (!m) throw new Error(`const ${name} not found`);
  let i = m.index + m[0].length;
  while (/\s/.test(src[i])) i++;
  if (!PAIRS[src[i]]) throw new Error(`const ${name}: no opener at ${src.slice(i, i + 12)}`);
  const end = matchDelimiter(src, i);
  return `export const ${name} = ` + src.slice(i, end + 1) + ';';
}

function extractRawLine(src, pattern) {
  // extract a `const NAME = <expr>;` whose expr may open with ( [ or {
  const m = src.match(pattern);
  if (!m) throw new Error(`pattern not found: ${pattern}`);
  let i = m.index + m[0].length;
  while (/\s/.test(src[i])) i++;
  if (!PAIRS[src[i]]) throw new Error(`no opener after pattern at offset ${i}`);
  const end = matchDelimiter(src, i);
  return 'export ' + src.slice(m.index, end + 1) + ';';
}

function extractFunction(src, name) {
  const m = src.match(new RegExp(`\\bfunction ${name}\\s*\\(`));
  if (!m) throw new Error(`function ${name} not found`);
  let i = m.index;
  while (src[i] !== '{') i++;
  const end = matchDelimiter(src, i);
  return 'export ' + src.slice(m.index, end + 1);
}

