const stripDanda = s => (s || '').replace(/[।॥.]+/g, '').trim();

function waveSvg(lineIast) {
  const syls = syllabifyIast(lineIast);
  if (!syls.length) return '';
  const W = Math.max(240, syls.length * 44 + 40), H = 96;
  const step = (W - 40) / syls.length;
  let pts = '', labels = '';
  syls.forEach((s, i) => {
    const x = 20 + step * i + step / 2;
    const guru = s.type === 'guru';
    const y = guru ? 14 : 62;
    pts += `${x},${y} `;
    labels += `<text x="${x}" y="88" text-anchor="middle" font-size="13" fill="${guru ? '#8B0000' : '#2C4A1E'}" font-family="ui-monospace,monospace">${esc(s.syl)}</text>`;
  });
  return `<svg class="wave" viewBox="0 0 ${W} ${H}" role="img" aria-label="syllable wave: guru high, laghu low">` +
    `<polyline points="${pts.trim()}" fill="none" stroke="#b07c18" stroke-width="2"/>` +
    pts.trim().split(' ').map(p => { const [x, y] = p.split(',');
      return `<circle cx="${x}" cy="${y}" r="4.5" fill="${y === '14' ? '#8B0000' : '#2C4A1E'}"/>`;
    }).join('') + labels + '</svg>';
}

